// Builds src/data/attack.json from MITRE ATT&CK's official STIX data on GitHub
// (github.com/mitre-attack/attack-stix-data): the Enterprise tactics, plus every
// technique ID (T1234 or T1234.001) that the slides' data files mention.
// Needs internet once; the presentation then uses the bundled file offline.
//   npm run attack                       # version 18.1, as in the learner guide
//   npm run attack -- --version=20.0     # a newer release
//   npm run attack -- --file=enterprise-attack-18.1.json   # a file you downloaded
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = Object.fromEntries(process.argv.slice(2).map((a) => {
  const [k, v] = a.replace(/^--/, '').split('=');
  return [k, v ?? true];
}));
const version = String(args.version ?? '18.1');
const url = `https://raw.githubusercontent.com/mitre-attack/attack-stix-data/master/enterprise-attack/enterprise-attack-${version}.json`;

let bundle;
if (args.file) {
  bundle = JSON.parse(readFileSync(String(args.file), 'utf8'));
} else {
  console.log(`attack: downloading ATT&CK ${version} from GitHub…`);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status} for ${url}`);
  bundle = await res.json();
}

// Technique IDs the slides and the Module 5 LAN game use, found in every data
// file except this tool's own output.
const dataDir = join(root, 'src/data');
const scanDirs = [dataDir, join(root, 'range/scenario')];
const wanted = new Set();
for (const dir of scanDirs) {
  if (!existsSync(dir)) continue;
  for (const name of readdirSync(dir).filter((f) => f.endsWith('.json') && f !== 'attack.json')) {
    for (const m of readFileSync(join(dir, name), 'utf8').matchAll(/"(T\d{4}(?:\.\d{3})?)"/g)) wanted.add(m[1]);
  }
}

const live = bundle.objects.filter((o) => !o.revoked && !o.x_mitre_deprecated);
const extId = (o) => o.external_references?.find((r) => r.source_name === 'mitre-attack');
const collection = bundle.objects.find((o) => o.type === 'x-mitre-collection');
const matrix = live.find((o) => o.type === 'x-mitre-matrix');
const tacticObjs = matrix.tactic_refs.map((ref) => live.find((o) => o.id === ref));
const tacticName = Object.fromEntries(tacticObjs.map((t) => [t.x_mitre_shortname, t.name]));

const techniques = {};
for (const id of [...wanted].sort()) {
  const t = live.find((o) => o.type === 'attack-pattern' && extId(o)?.external_id === id);
  if (!t) {
    console.warn(`attack: ${id} is not in ATT&CK ${version} (revoked, deprecated or mistyped)`);
    continue;
  }
  const parentId = id.includes('.') ? id.split('.')[0] : null;
  const parent = parentId ? live.find((o) => o.type === 'attack-pattern' && extId(o)?.external_id === parentId) : null;
  const summary = t.description.replace(/\(Citation:[^)]*\)/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/\s+/g, ' ').split(/(?<=\.)\s/)[0];
  techniques[id] = {
    name: parent ? `${parent.name}: ${t.name}` : t.name,
    tactics: (t.kill_chain_phases ?? []).filter((k) => k.kill_chain_name === 'mitre-attack').map((k) => tacticName[k.phase_name] ?? k.phase_name),
    url: extId(t).url,
    summary,
  };
}

const out = {
  _readme: 'Generated by tools/attack-extract.mjs from MITRE ATT&CK (github.com/mitre-attack/attack-stix-data). Do not edit by hand: run npm run attack.',
  copyright: `© ${new Date(collection?.modified ?? Date.now()).getFullYear()} The MITRE Corporation. This work is reproduced and distributed with the permission of The MITRE Corporation.`,
  version: collection?.x_mitre_version ?? version,
  released: (collection?.modified ?? '').slice(0, 10),
  source: url,
  tactics: tacticObjs.map((t) => ({ id: extId(t).external_id, name: t.name })),
  techniques,
};
writeFileSync(join(dataDir, 'attack.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`attack: ATT&CK ${out.version} (${out.released}): ${out.tactics.length} tactics, ${Object.keys(techniques).length} techniques → src/data/attack.json`);
